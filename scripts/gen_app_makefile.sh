#!/bin/sh
# gen_app_makefile.sh — Generate a Makefile for an ooke application.
#
# Scans pages/ for handler modules, generates _handlers.tk, _serve_main.tk and
# _serve.tkc.toml, and produces a Makefile that compiles everything into a
# per-app binary. `ooke compile [path]` runs this, then `make -f Makefile.serve`.
#
# Usage: ./gen_app_makefile.sh <project_dir> [ooke_dir] [toke_dir]
#
#   ooke_dir defaults to the checkout this script is in; toke_dir to
#   $TOKE_ROOT, else <ooke_dir>/../toke — the same default as ooke's Makefile.
#
# Output: <project_dir>/Makefile.serve (generated build file)
#
# Story 134.44. The generated program had fallen far behind `ooke serve`:
# `Ok:`/`Err:` match arms (pre-v0.4), `config.cfgdefault()` (it lives in
# ooke.cli), empty [tls] strings and no [log] — it did not compile, and even
# the Makefile could not have linked it (a stdlib list of its own that lacked
# every glue file, and five of ooke's modules). Now:
#
#   * the serve main is one call to cli.runserve — the SAME function `ooke
#     serve` runs, so a malformed ooke.toml is refused (134.42), [tls] and
#     [log] are applied (134.40) and a bind failure exits non-zero (134.40),
#     with nothing restated here to drift again;
#   * the stdlib/vendor sources, flags and ooke modules come from ooke's own
#     `make print-build-vars` (the single source 134.5 made for anything that
#     links against ooke), minus ooke's handler registry, which the app's
#     generated _handlers.tk replaces;
#   * the capability grant (ADR-0010) is written beside the main: fs_read,
#     fs_write (logs) and net — a serve binary spawns nothing.

set -e

PROJECT=$(cd "${1:-.}" && pwd)
OOKE_DIR=$(cd "${2:-$(dirname "$0")/..}" && pwd)
TOKE_DIR=$(cd "${3:-${TOKE_ROOT:-$OOKE_DIR/../toke}}" && pwd) || {
  echo "gen_app_makefile: no toke checkout (pass it as the third argument or set TOKE_ROOT)" >&2
  exit 1
}

APP_NAME=$(grep '^name' "$PROJECT/ooke.toml" 2>/dev/null | head -1 | sed 's/.*= *"//; s/".*//' || true)
[ -z "$APP_NAME" ] && APP_NAME="app"

# Build variables: ooke's Makefile is the only place they are written down.
VARS=$(make -s --no-print-directory -C "$OOKE_DIR" print-build-vars TOKE_ROOT="$TOKE_DIR") || {
  echo "gen_app_makefile: 'make print-build-vars' failed in $OOKE_DIR" >&2
  exit 1
}
eval "$VARS"
[ -n "$TKC" ] && [ -n "$STDLIB_SRCS" ] && [ -n "$OOKE_LL" ] || {
  echo "gen_app_makefile: print-build-vars in $OOKE_DIR returned no TKC/STDLIB_SRCS/OOKE_LL" >&2
  exit 1
}
APP_OOKE_LL=""
for m in $OOKE_LL; do
  case $m in
    */handlers) ;;                       # replaced by the app's own registry
    /*) APP_OOKE_LL="$APP_OOKE_LL $m" ;;
    *)  APP_OOKE_LL="$APP_OOKE_LL $OOKE_DIR/$m" ;;
  esac
done

# Step 1: Generate _handlers.tk
"$OOKE_DIR/scripts/gen_handlers.sh" "$PROJECT/pages" "$PROJECT/_handlers.tk"

# Story 138.7 (O-2): the registry imports every page plus std.http, and toke
# caps a module at 32 imports by default (E9010: "compiler limit exceeded: too
# many imports"), so an app with more than 31 pages did not compile.  Raise the
# cap for this one module to exactly its import count, and only when the
# default is too small.  (ooke's own Makefile passes no such flag: its registry
# holds ooke's built-in handler pages, which it compiles itself -- 134.47.)
NIMPORTS=$(grep -c '^i=' "$PROJECT/_handlers.tk" || true)
HANDLERS_MAXIMP=""
if [ "${NIMPORTS:-0}" -gt 32 ]; then HANDLERS_MAXIMP="--max-imports=$NIMPORTS "; fi

# Step 2: Collect page handler .tk files
PAGE_HANDLERS=""
for tkfile in $(find "$PROJECT/pages" -name '*.tk' -type f 2>/dev/null | sort); do
  has_get=0; has_post=0
  grep -q 'f=get(' "$tkfile" 2>/dev/null && has_get=1
  grep -q 'f=post(' "$tkfile" 2>/dev/null && has_post=1
  if [ "$has_get" -eq 1 ] || [ "$has_post" -eq 1 ]; then
    PAGE_HANDLERS="$PAGE_HANDLERS $tkfile"
  fi
done

# Step 3: Generate _serve_main.tk and its capability grant
cat > "$PROJECT/_serve_main.tk" << 'MAIN'
(* GENERATED by ooke scripts/gen_app_makefile.sh (story 134.44). Do not edit.
   `ooke serve` and this binary run the same cli.runserve, so the config,
   [log], [tls] and bind-failure behaviour cannot drift apart. *)
m=app.main;
i=args:std.args;
i=cli:ooke.cli;

f=main():i64{
  let projectdir=mt args.get(1) {$ok:v v;$err:e "."};
  <cli.runserve(projectdir)
};
MAIN

cat > "$PROJECT/_serve.tkc.toml" << 'CAPS'
# GENERATED by ooke scripts/gen_app_makefile.sh (story 134.44). Do not edit.
# Capability grant (ADR-0010) for the per-app serve binary: read the project,
# write its [log] files, listen. It spawns nothing.
[capabilities]
fs_read = true
fs_write = true
net = true
enforce = true
CAPS

# Step 4: Generate Makefile.serve
PAGE_LL=""
PAGE_INC=""
PAGE_TKI_RULES=""
for tkfile in $PAGE_HANDLERS; do
  rel=${tkfile#$PROJECT/}
  relpages=${tkfile#$PROJECT/pages}
  modname=$(echo "$relpages" | sed 's|^/||; s|\.tk$||; s|/||g')   # as gen_handlers.sh names it
  [ -z "$modname" ] && modname="index"
  PAGE_LL="$PAGE_LL build/ooke/$modname"
  dir=$(dirname "$rel")
  case " $PAGE_INC " in *" -I $dir "*) ;; *) PAGE_INC="$PAGE_INC -I $dir" ;; esac
  PAGE_TKI_RULES="${PAGE_TKI_RULES}
build/ooke/${modname}: ${rel} \$(OOKE_LL) | build/ooke
	\$(TKC) --emit-interface --emit-llvm -I \$(OOKE_DIR)/src --out build/ooke/${modname} ${rel}
"
done

cat > "$PROJECT/Makefile.serve" << MAKEFILE
# Generated by ooke — per-app serve binary build (story 134.44). Do not edit.
# Regenerate with: ooke compile $PROJECT
# (or $OOKE_DIR/scripts/gen_app_makefile.sh $PROJECT $OOKE_DIR $TOKE_DIR)

TKC       := $TKC
TOKE_ROOT := $TOKE_DIR
OOKE_DIR  := $OOKE_DIR

BIN := build/$APP_NAME

# From \`make -C \$(OOKE_DIR) print-build-vars\` at generation time.
STDLIB_SRCS := $STDLIB_SRCS
VENDOR_SRCS := $VENDOR_SRCS
CFLAGS      := $CFLAGS
LDFLAGS     := $LDFLAGS
LIBS        := $LIBS

# ooke's modules, without its handler registry (the app's _handlers.tk replaces it)
OOKE_LL := $APP_OOKE_LL

# App page handler modules
PAGE_LL := $PAGE_LL
PAGE_INC := $PAGE_INC

.PHONY: all clean

all: \$(BIN)

build/ooke:
	mkdir -p build/ooke

\$(OOKE_LL):
	\$(MAKE) --no-print-directory -C \$(OOKE_DIR) TOKE_ROOT=\$(TOKE_ROOT) interfaces

# Page handler modules (tkc writes each .tki beside its source)
$PAGE_TKI_RULES
# Generated handlers module
build/ooke/handlers: _handlers.tk \$(PAGE_LL) | build/ooke
	\$(TKC) ${HANDLERS_MAXIMP}--emit-interface --emit-llvm \$(PAGE_INC) -I \$(OOKE_DIR)/src --out build/ooke/handlers _handlers.tk

# Main entry point: cli.runserve, with the serve binary's capability grant
build/main.ll: _serve_main.tk _serve.tkc.toml build/ooke/handlers \$(OOKE_LL) | build/ooke
	\$(TKC) --config=_serve.tkc.toml --emit-llvm -I \$(OOKE_DIR)/src --out build/main.ll _serve_main.tk

# Final binary
\$(BIN): build/main.ll build/ooke/handlers \$(PAGE_LL) \$(OOKE_LL)
	clang \$(CFLAGS) \$(LDFLAGS) \\
	  -x ir build/main.ll build/ooke/handlers \$(PAGE_LL) \$(OOKE_LL) \\
	  -x c \$(STDLIB_SRCS) \$(VENDOR_SRCS) \\
	  -o \$@ \$(LIBS)

clean:
	rm -rf build/
MAKEFILE

echo "Generated: $PROJECT/Makefile.serve"
echo "Build with: make -f Makefile.serve -C $PROJECT"
echo "Run with: (cd $PROJECT && build/$APP_NAME .)"
